// 「该不该在这个文档上挂编辑器」的判定 —— 单独一个文件，只为一件事：**能单测**。
//
// 为什么值得单拉出来：这两条判据都带着「看代码看不出来、只有真机会暴露」的陷阱
// （见下面第二条），把它们埋在 `content.ts` 里就只能靠探针量、不能靠单测钉住。

/**
 * 该不该在这个文档上挂编辑器。
 *
 * ── 判据 ①：`contentType` 必须是 `text/html` ──
 * `file:///*` 也会匹配 `.svg` / `.xml` / 纯文本等文档，在那些文档上挂编辑器没有意义，
 * 甚至可能把 XML 结构改坏。`document.contentType` 在 `file://` 下由扩展名与内容嗅探决定，
 * 是最直接的一道闸。
 *
 * ── 判据 ②：🔴 `path` 不能以 `/` 结尾（= 不能是目录）──
 * 这是 2026-09-23 加「保存后打开文件夹」时才暴露出来的：Chrome 打开一个 `file://` **目录**
 * 时会**自己渲染一张目录索引页**，而那张页面的 `contentType` 同样是 `text/html`
 * ⇒ 判据 ① 拦不住它。于是「保存 → 自动打开文件夹」开出来的**正是**那个页面，
 * 而我们的工具条会直接压在用户想看的文件列表上（实测：`#ep-root` 已挂载）。
 *
 * 用它自己的话讲：**我们刚帮用户打开文件夹，就顺手在他的文件夹列表上盖了一层工具栏。**
 *
 * 判据取「`pathname` 以 `/` 结尾」而不是去认标题文案（如「…的索引」）：
 *   · 文件 URL **不可能**以斜杠结尾 —— 目录 URL 必然以斜杠结尾。这是 URL 层面的硬事实，
 *     不是某个版本、某个语言的行为；
 *   · 标题文案是**中文 locale 的产物**（`C:\…\ 的索引`），换个界面语言就失效，
 *     而且 Chrome 随时可以改它的措辞。拿它当判据等于把回归网挂在一句会变的文案上。
 *
 * ⚠️ 副作用要说清：目录页上**没有**编辑器了，所以用户也没法在目录页上用任何功能。
 * 这是对的 —— 那张页面的内容是「文件夹里有什么」，不是一份可编辑的文档；
 * 想改哪个文件，点进去就是。
 */
export function isEditableHtml(contentType: string, path: string): boolean {
  if (path.endsWith('/')) return false;
  return contentType === 'text/html';
}
